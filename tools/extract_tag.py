"""Recover tag/corner descriptors and tables from the supplied US rev 2 set."""
import argparse
import json
import struct
import zipfile
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('archive', type=Path)
    parser.add_argument('--output', type=Path, default=Path('src/data/tag-tables.js'))
    args = parser.parse_args()
    with zipfile.ZipFile(args.archive) as archive:
        even, odd = archive.read('31a14-2.ic18'), archive.read('31a13-2.ic19')
    b = bytearray(len(even) * 2)
    b[::2], b[1::2] = even, odd
    word = lambda a: struct.unpack_from('>H', b, a)[0]
    long = lambda a: struct.unpack_from('>I', b, a)[0]
    words = lambda a, n: list(struct.unpack_from(f'>{n}H', b, a))

    def descriptor(a):
        handler, mode, count = struct.unpack_from('>IHH', b, a)
        if not mode:
            count = 0
        return {'source': a, 'update': handler, 'mode': mode,
                'delays': words(a + 8, count), 'poses': words(a + 8 + count * 2, count)}

    data = {
        'actions': {str(a): descriptor(long(0x11854 + a * 4)) for a in (13,27,55,76,77,78,79,89,97,102)},
        'manualAssistWeights': [[list(b[long(0x2259e+i*4)+j*2:long(0x2259e+i*4)+j*2+2]) for j in range(3)] for i in range(12)],
        'manualNullSeverity': word(0x70),
        'proneAssistTimers': words(0x204a2,3),
        'benchThresholds': words(0xeff4,12),
        'computerHitThresholds': list(b[0xf00c:0xf018]),
        'boostTimers': words(0xf018,10),
        'tagPositions': [words(0x17af4 + i * 4, 2) for i in range(2)],
        'entryPositions': [words(0x17cc8 + i * 4, 2) for i in range(2)],
        'holdPositions': [words(0x189ae + i * 4, 2) for i in range(2)],
        'mountAnimations': [descriptor(long(0x111c6 + i * 4)) for i in range(10)],
        'mountPositions': [words(0x11408 + i * 4, 2) for i in range(10)],
        'alternateMountPositions': [words(0x11418 + i * 4, 2) for i in range(2)],
        'waitPositions': [words(0x11496 + i * 4, 2) for i in range(10)],
        'waitPoses': list(b[0x114be:0x114c2]),
        'dismountAnimations': [descriptor(a) for a in (0x114c2,0x114e6,0x11502)],
        'apronRecoveryTimes': words(0x10b54,12),
        'assistTimers': words(0x206e0,3),
        'jumpMoves': [list(b[a:a + 12]) for a in (0x1e1b8,0x1e1c4)],
        'jumpCaptureWeights': list(b[0x1e1b6:0x1e1b8]),
        'benchAttackWeights': [list(b[0x1c71c + i * 4:0x1c720 + i * 4]) for i in range(10)],
        'playerPalettes': [[words(long(base + i * 4),16) for i in range(12)] for base in (0xbd28,0xbd58)],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('// Generated by tools/extract_tag.py from wwfwfest US rev 2.\n'
                          'export const tagTables = ' + json.dumps(data,indent=2) + ';\n', encoding='utf-8')


if __name__ == '__main__':
    main()
