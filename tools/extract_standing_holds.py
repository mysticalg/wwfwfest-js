"""Recover standing hold descriptors and tables from the supplied US rev 2 set."""
import argparse
import json
import struct
import zipfile
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('archive', type=Path)
    parser.add_argument('--output', type=Path, default=Path('src/data/standing-hold-tables.js'))
    args = parser.parse_args()
    with zipfile.ZipFile(args.archive) as archive:
        even, odd = archive.read('31a14-2.ic18'), archive.read('31a13-2.ic19')
    b = bytearray(len(even) * 2)
    b[::2], b[1::2] = even, odd
    word = lambda a: struct.unpack_from('>H', b, a)[0]
    long = lambda a: struct.unpack_from('>I', b, a)[0]
    words = lambda a, n: list(struct.unpack_from(f'>{n}H', b, a))

    def descriptor(a):
        handler, mode, count = struct.unpack_from('>IHH', b, a)
        if not mode:
            count = 0
        return {'source': a, 'update': handler, 'mode': mode,
                'delays': words(a + 8, count), 'poses': words(a + 8 + count * 2, count)}

    data = {
        'actions': {str(a): descriptor(long(0x11854+a*4)) for a in (28,29,82,83,87,88,109,115,116,118)},
        'variants': {'punch': descriptor(0x1808c), 'kick': descriptor(0x18098), 'sideImpact': descriptor(0x17f62)},
        'classes': list(b[0x1803a:0x18046]),
        'offsets': list(struct.unpack_from('>5b', b, 0x18148)),
        'sideOffsets': list(struct.unpack_from('>5b', b, 0x18046)),
        'attackTimers': words(0x2025e,3),
        'victimTimers': words(0x204a2,3),
        'sideVictimTimers': words(0x20334,3),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('// Generated by tools/extract_standing_holds.py from US rev 2.\n'
                          'export const standingHoldTables = ' + json.dumps(data,indent=2) + ';\n', encoding='utf-8')

if __name__ == '__main__':
    main()
