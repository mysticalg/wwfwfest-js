"""Extract editable computer-opponent tables from the supplied US rev 2 set."""
import argparse
import json
import struct
import zipfile
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('archive', type=Path)
    parser.add_argument('--output', type=Path, default=Path('src/data/ai-tables.js'))
    args = parser.parse_args()
    with zipfile.ZipFile(args.archive) as archive:
        even, odd = archive.read('31a14-2.ic18'), archive.read('31a13-2.ic19')
    program = bytearray(len(even) * 2)
    program[::2], program[1::2] = even, odd
    long = lambda address: struct.unpack_from('>I', program, address)[0]
    words = lambda address, count: list(struct.unpack_from(f'>{count}H', program, address))

    def move_rows(group):
        result = []
        for kind in range(12):
            entry = long(long(0x20bda + kind * 4) + group * 4)
            facings = []
            for facing in range(2):
                regions = []
                for region in range(3):
                    address = long(long(entry + facing * 4) + region * 4)
                    count = program[address]
                    regions.append({'source': address,
                        'actions': list(program[address + 1:address + 1 + count]),
                        'weights': [list(program[address + 1 + count * (severity + 1):
                                                address + 1 + count * (severity + 2)])
                                    for severity in range(3)]})
                facings.append(regions)
            result.append(facings)
        return result

    data = {
        'clinchMoves': move_rows(1),
        'headlockMoves': move_rows(9),
        'assistanceMoves': list(program[0x1e376:0x1e382]),
        'clinchStrikeWeights': list(program[0x1e284:0x1e286]),
        'clinchStrikeDelays': list(program[0x1e286:0x1e290]),
        'carryWeights': [[[list(program[base + program[0x1dc44 + round] + severity * 2:
                                               base + program[0x1dc44 + round] + severity * 2 + 2])
                          for severity in range(3)] for round in range(10)]
                        for base in (0x1dbfc, 0x1dc20)],
        'rumbleCarryWeights': list(program[0x1dbfa:0x1dbfc]),
        'bossCarryWeights': [list(program[0x1dc4e + severity * 2:0x1dc50 + severity * 2]) for severity in range(3)],
        'heldEscapeTimes': [words(long(0x1e79c + kind * 4), 3) for kind in range(6)],
        'tagStaggerWeights': list(program[0x1e67e:0x1e680]),
        'rumbleFrontRecoveryWeights': [list(program[0x1d06e + severity * 2:0x1d070 + severity * 2]) for severity in range(3)],
        'rumbleGroundRecoveryWeights': [list(program[0x1d068 + severity * 2:0x1d06a + severity * 2]) for severity in range(3)],
        'frontRecoveryWeights': [[list(program[long(0x22fa4 + round * 4) + severity * 2:
                                             long(0x22fa4 + round * 4) + severity * 2 + 2]) for severity in range(3)] for round in range(10)],
        'groundRecoveryWeights': [[[list(program[long(base + round * 4) + severity * 2:
                                                long(base + round * 4) + severity * 2 + 2]) for severity in range(3)] for round in range(10)]
                                  for base in (0x2319e, 0x231ea, 0x22ff6)],
        'recoveryAttackIds': list(program[0x1d074:0x1d07b]),
        'recoveryAttemptWeights': [[list(program[long(0x2303c + kind * 4) + count * 2:
                                                 long(0x2303c + kind * 4) + count * 2 + 2]) for count in range(6)] for kind in range(7)],
        'backAttackRecoveryWeights': [[list(program[long(0x2309c + round * 4) + count * 2:
                                                   long(0x2309c + round * 4) + count * 2 + 2]) for count in range(5)] for round in range(10)],
        'actionHandlers': [long(0x1d23e + action * 4) for action in range(144)],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('// Generated by tools/extract_ai.py from wwfwfest US rev 2.\n'
                          'export const aiTables = ' + json.dumps(data, indent=2) + ';\n', encoding='utf-8')


if __name__ == '__main__':
    main()
